// Writes the play scripts that drive the real UI through whole games, from
// the shipped rules (js/rules.js) so they stay in step with them:
// - tests/native/journey.play: Journey stage 1 (First Hand, seeded) played
//   to its results, the player taking the hint's pass and plays (clicking
//   the cards by name and the Pass button); the AI seats choose as the
//   client asks them (seat by seat after the player's pass, deterministic
//   from the state), so the whole match is known here. Then Play again.
// - tests/native/lessons.play: the six Learn lessons, each by its action.
//   node tools/gen-play.mjs
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import '../js/rng.js';
import '../js/rules.js';
import '../js/content.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const R = globalThis.HFRules, C = globalThis.HFContent;
const name = (c) => R.cardName(c);

// ---- Journey 1 to its results ---------------------------------------------------------------
{
  const level = C.JOURNEY[0];
  let s = R.createGame(level);
  const lines = [
    '# Journey stage 1 (First Hand) played to its results by the hint (generated by',
    '# tools/gen-play.mjs from js/rules.js): the cards clicked by name, the Pass button.',
    'until 300 =Play',
    'frames 10',
    'click =Play',
    'until 60 Modes',
    'frames 10',
    'click =Journey',
    'until 60 Forty stages',
    'frames 10',
    'click 1. First Hand',
    'until 120 You (13)',
    'frames 150',
    'save journey-deal',
  ];
  let guard = 0, plays = 0, rounds = 0;
  while (!s.terminal && guard++ < 2000) {
    if (s.phase === 'pass' && s.passes[0] === null && s.actor === 0) {
      const h = R.hint(s, 0);
      lines.push(`until 1200 Pass 0/${s.cfg.passCount}`, 'frames 5');
      h.cards.forEach((c, i) => lines.push(`click =${name(c)}`, 'frames 5', `until 30 Pass ${i + 1}/${s.cfg.passCount}`));
      lines.push('frames 5', `click =Pass ${s.cfg.passCount}/${s.cfg.passCount}`, 'frames 5');
      if (rounds === 0) lines.push('frames 2', 'save journey-passed');
      s = R.applyCommand(s, { type: 'pass', p: 0, cards: h.cards }).state;
      continue;
    }
    if (s.phase === 'play' && s.actor === 0) {
      const h = R.hint(s, 0);
      lines.push('until 1200 Your turn', 'frames 5', `click =${name(h.card)}`, 'frames 5');
      const before = s.round;
      s = R.applyCommand(s, { type: 'play', p: 0, card: h.card }).state;
      plays++;
      if (plays === 3) lines.push('frames 60', 'save journey-trick');
      if (s.round !== before) rounds++;
      continue;
    }
    const cmd = R.aiChoose(s, s.actor);
    const before = s.round;
    s = R.applyCommand(s, cmd).state;
    if (s.round !== before) rounds++;
  }
  if (!s.terminal) throw new Error('match did not end');
  const t = s.terminal;
  const won = t.winners.includes(0);
  const head = won ? 'You win the table.' : `${C.seatName(t.winner)} takes the table.`;
  lines.push(
    `# ${s.round} rounds, ${plays} plays; final scores ${t.scores.join(' / ')}`,
    `until 3000 ${head}`,
    'frames 60',
    `expect You: ${t.scores[0]}`,
    `expect Win the match — ${won ? 'achieved' : 'not met'}`,
    'save journey-results',
    'frames 150',
    'click =Play again',
    'until 120 Pass 0/3',
    'frames 10',
    'expect You: 0',
    'save journey-again',
  );
  writeFileSync(join(root, 'tests/native/journey.play'), lines.join('\n') + '\n');
  console.log(`journey.play: ${s.round} rounds, ${plays} plays, ${won ? 'won' : 'lost'} ${t.scores.join('/')}`);
}

// ---- the six lessons --------------------------------------------------------------------------
{
  const L = C.tutorialLessons();
  const lines = [
    '# The six Learn lessons, each finished by its action (generated by tools/gen-play.mjs).',
    'until 300 =Play',
    'frames 10',
    'click =Play',
    'until 60 Modes',
    'frames 10',
    'click =Learn',
    'until 60 Six lessons',
    'frames 10',
    'click 1. Follow the suit',
  ];
  const steps = {
    t1: ['until 120 Your turn', 'frames 10', 'click =7♦'],
    t2: (() => {
      const st = R.createGame(L[1].cfg);
      const h = R.hint(st, 0);
      const out = ['until 120 Pass 0/3', 'frames 10', 'click =Hint', 'frames 5', 'until 30 Pass 3/3', 'frames 5', 'save lessons-pass-hint', 'click =Pass 3/3'];
      void h;
      return out;
    })(),
    t3: ['until 120 Your turn', 'frames 10', 'click =2♠'],
    t4: ['until 120 Your turn', 'frames 10', 'click =Q♠'],
    t5: ['until 120 Your turn', 'frames 10', 'click =A♦'],
    t6: ['until 120 Your turn', 'frames 10', 'click =5♣', 'frames 10', 'key KeyU 1'],
  };
  L.forEach((l, i) => {
    lines.push(...steps[l.id], 'until 600 Lesson complete.', 'frames 10', `expect ${l.title} — done.`);
    if (i === 0) lines.push('save lessons-complete');
    if (i < L.length - 1) lines.push('click =Next lesson');
    else lines.push('expect Back to lessons', 'click =Back to lessons', 'until 60 Six lessons', 'frames 30', 'save lessons-list');
  });
  writeFileSync(join(root, 'tests/native/lessons.play'), lines.join('\n') + '\n');
  console.log(`lessons.play: ${L.map((l) => l.title).join(', ')}`);
}
